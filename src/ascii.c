#include "wkw.h"

void	draw_art(int y, int x, uint64_t v, int len)
{
	static const char	*font[10][3] = {
		{" _ ", "| |", "|_|"}, {"   ", "  |", "  |"},
		{" _ ", " _|", "|_ "}, {" _ ", " _|", " _|"},
		{"   ", "|_|", "  |"}, {" _ ", "|_ ", " _|"},
		{" _ ", "|_ ", "|_|"}, {" _ ", "  |", "  |"},
		{" _ ", "|_|", "|_|"}, {" _ ", "|_|", " _|"}
	};
	uint64_t			div = 1;

	for (int i = 1; i < len; i++)
		div *= 10;
	for (int i = 0; i < len; i++, div /= 10)
		for (int row = 0; row < 3; row++)
			mvaddstr(y + row, x + i * 3, font[(v / div) % 10][row]);
}
